#!/bin/bash
set -euo pipefail

mysql --protocol=socket -uroot -p"${MYSQL_ROOT_PASSWORD}" <<EOSQL
CREATE DATABASE IF NOT EXISTS cozynest_identity CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
CREATE DATABASE IF NOT EXISTS cozynest_listing CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
CREATE DATABASE IF NOT EXISTS cozynest_booking CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
CREATE DATABASE IF NOT EXISTS cozynest_billing CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
CREATE DATABASE IF NOT EXISTS cozynest_communication CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
CREATE DATABASE IF NOT EXISTS cozynest_admin CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

CREATE USER IF NOT EXISTS '${IDENTITY_DB_USER}'@'%' IDENTIFIED BY '${IDENTITY_DB_PASSWORD}';
GRANT ALL PRIVILEGES ON cozynest_identity.* TO '${IDENTITY_DB_USER}'@'%';

CREATE USER IF NOT EXISTS '${LISTING_DB_USER}'@'%' IDENTIFIED BY '${LISTING_DB_PASSWORD}';
GRANT ALL PRIVILEGES ON cozynest_listing.* TO '${LISTING_DB_USER}'@'%';

CREATE USER IF NOT EXISTS '${BOOKING_DB_USER}'@'%' IDENTIFIED BY '${BOOKING_DB_PASSWORD}';
GRANT ALL PRIVILEGES ON cozynest_booking.* TO '${BOOKING_DB_USER}'@'%';

CREATE USER IF NOT EXISTS '${BILLING_DB_USER}'@'%' IDENTIFIED BY '${BILLING_DB_PASSWORD}';
GRANT ALL PRIVILEGES ON cozynest_billing.* TO '${BILLING_DB_USER}'@'%';

CREATE USER IF NOT EXISTS '${COMMUNICATION_DB_USER}'@'%' IDENTIFIED BY '${COMMUNICATION_DB_PASSWORD}';
GRANT ALL PRIVILEGES ON cozynest_communication.* TO '${COMMUNICATION_DB_USER}'@'%';

CREATE USER IF NOT EXISTS '${ADMIN_DB_USER}'@'%' IDENTIFIED BY '${ADMIN_DB_PASSWORD}';
GRANT ALL PRIVILEGES ON cozynest_admin.* TO '${ADMIN_DB_USER}'@'%';

FLUSH PRIVILEGES;
EOSQL